/**
 * Exports the local catalogue (categories, agents, content, activity) as SQL
 * INSERT statements so it can be loaded into D1:
 *   npm run db:export-sql && npx wrangler d1 execute x86xx --local --file .data/seed.sql
 * Jobs and generated content are not exported: they belong to the environment that ran them.
 */
import { writeFile } from "node:fs/promises";
import { getServices } from "../src/server/container";
import { SqliteDatabase } from "../src/server/db/sqlite";

const TABLES: Record<string, string> = {
  categories: "SELECT * FROM categories",
  agents: "SELECT * FROM agents",
  content: "SELECT * FROM content WHERE source = 'seed'",
  activity_log: "SELECT * FROM activity_log WHERE job_id IS NULL",
};
const q = (v: unknown) => (v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

async function main() {
  const s = await getServices();
  const raw = (s.db as SqliteDatabase).raw;
  const out: string[] = ["-- generated by scripts/export-seed-sql.ts", "PRAGMA defer_foreign_keys = true;"];
  for (const [t, sql] of Object.entries(TABLES)) {
    const rows = raw.prepare(sql).all() as Record<string, unknown>[];
    if (!rows.length) continue;
    const cols = Object.keys(rows[0]);
    for (const r of rows) out.push(`INSERT OR IGNORE INTO ${t} (${cols.join(", ")}) VALUES (${cols.map((c) => q(r[c])).join(", ")});`);
  }
  const file = ".data/seed.sql";
  await writeFile(file, out.join("\n") + "\n");
  console.log(`wrote ${file} (${out.length - 2} rows)`);
}
main().catch((e) => { console.error(e); process.exit(1); });
